				<span class="title"><em>ABOUT</em></span>
				<div class="content-box">
					Andre Murray hails from Los Angeles, California, one of the most prominent basketball cities in the United States. In a city ripe with talent, Andre paved his way to the top as a true student of the game. Through his own personal commitment to develop as a player and his uncanny ability to imitate the best in the game, Andre developed into a remarkably versatile, creative, and powerful force on the court.
					<div id="more-about" class="hidden">
						<p>
							Andre first began to build a reputation in the Los Angeles basketball community while attending College of the Canyons in Santa Clarita. After just two seasons, Andre was ranked 7th All-Time Scoring for the College of the Canyons after totaling 1,073 points. His ability to score resulted in his being named to the All-Western State Conference First Team during both his freshman and sophomore years. He also earned state recognition being named to the All-Freshman First Team during his first year, and the All-State First Team during his second year.
						</p>
						<p>
							In the fall of 2007, Andre joined a promising, up-and-coming Division I team with the Portland State University Vikings. During his two seasons with the Vikings, Andre played a fundamental role as the team won the Big Sky Conference Championship, set a school record for victories, and made appearances in the NCAA Tournament for the first time in school history for two consecutive years. Andre started 55 out of the 65 total games played during the two seasons and was only one of two players to start every game during his senior season.
						</p>
						<p>
							Already an established offensive threat, Andre led the team his senior season with 21 double-figure scoring games and ranked 10th All-Time in Three-Pointers made in Portland State basketball history. Andre also proved to be equally formidable on the defensive end. After just two seasons, Andre ranked 9th All-Time in Steals made in Portland State history and was named the Portland State Defensive Player of the Year during his senior season. The conference recognized his presence on the court during his senior season by naming him to both the Second-Team All-Big Sky Conference Team and Big Sky All-Tournament Team.
						</p>
						<p>
							In 2009, following his collegiate achievements and graduation, Andre was selected to join the Bochum Astro Stars in Germany. Upon arrival, Andre immediately established himself as a key player for the team and a respected public figure in the city of Bochum. Within two months, Andre was voted by the public for October's "Sportsman of the Month" Award. His versatility and ability to quickly adapt to the system of play while incorporating his own ingenuity and flare on the court led to him becoming a serious threat. He completed the season ranked amongst the league’s top ten in scoring and set the team record for steals with 81 steals on the season.
						</p>
						<p>
							Upon returning to the States, Andre joined the Vancouver Volcanoes in the International Basketball League. In this league, Andre continued to impress by leading his team to the semi-finals having posted over 30 points in seven games and a season high of 40 points against the USA All-Stars. Ranked amongst the league’s top five in scoring, Andre was named by the IBL to the 2010 Second Team and chosen to join the 2010 IBL All-Star Team in just his first season.
						</p>
						<p>
							Impressed with his performance during his first season in Europe, Germany’s Bochum Astro Stars decided to re-sign Andre for the following season. Again, he played a crucial role in leading Bochum to an improved winning record and landing the team in second place in the league standings. Andre received a lot of public admiration when he scored a game winning basket at the buzzer from his own end of the court against the City Basket Recklinghausen.
						</p>
